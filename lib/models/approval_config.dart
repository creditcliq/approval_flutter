import 'user_data.dart';

/// Target environment for the verification API
enum ApprovalEnvironment { development, production }

/// Verification modules supported by CreditChek Approval
enum ApprovalModule { identity, liveliness, income, recova, credit }

/// Runtime configuration for launching CreditChek Approval.
///
/// Starting with the dynamic configuration update, [modules] and [environment]
/// are dynamically retrieved from your dashboard widget configuration via [widgetId].
class ApprovalConfig {
  /// Your CreditChek public API key
  final String publicKey;

  /// Unique session UUID generated by your backend via /v1/auth/widget-session/create
  final String sessionId;

  /// Widget configuration ID from your CreditChek dashboard
  final String widgetId;

  /// Optional pre-fill data for the user (BVN, NIN, name, email, phone, etc.)
  final AUserData? userData;

  const ApprovalConfig({
    required this.publicKey,
    required this.sessionId,
    required this.widgetId,
    this.userData,
  });

  Map<String, dynamic> toMap() {
    return {
      'publicKey': publicKey,
      'sessionId': sessionId,
      'widgetId': widgetId,
      if (userData != null) 'userData': userData!.toMap(),
    };
  }
}
